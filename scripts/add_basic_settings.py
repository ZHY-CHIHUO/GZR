def is_leaf(value):
    return isinstance(value, dict) and any(key in value for key in ("intro", "desc", "sections", "aliases"))


def count_leaves(data):
    def walk(node):
        if not isinstance(node, dict):
            return 0
        return sum((1 if is_leaf(value) else 0) + walk(value) for value in node.values() if isinstance(value, dict))

    return sum(walk(node) for category, node in data.items() if category != "_deleted")


def validate(data):
    basic = data.get("基本设定")
    if not isinstance(basic, dict):
        raise ValueError("missing 基本设定")
    if "第一卷" in basic:
        raise ValueError("基本设定 must not retain the 第一卷 subgroup")
    expected = [name for _chapter, name, _desc in CHAPTERS]
    if not set(expected).issubset(basic):
        missing = [name for name in expected if name not in basic]
        raise ValueError(f"missing 基本设定 entries: {', '.join(missing)}")
    for _chapter, name, _desc in CHAPTERS:
        entry = basic[name]
        if not is_leaf(entry):
            raise ValueError(f"{name} is not a wiki leaf")
        if entry.get("section") != "基本设定":
            raise ValueError(f"{name} must not expose a chapter-number label")
    return len(basic)


def flatten_basic_settings(data):
    basic = data.get("基本设定")
    if not isinstance(basic, dict):
        raise ValueError("missing 基本设定")
    volume = basic.get("第一卷")
    if volume is None:
        changed = False
        for _chapter, name, _desc in CHAPTERS:
            if name in basic and is_leaf(basic[name]) and basic[name].get("section") != "基本设定":
                basic[name]["section"] = "基本设定"
                changed = True
        validate(data)
        return changed
    if not isinstance(volume, dict):
        raise ValueError("基本设定 / 第一卷 is not a group")
    extra_groups = [name for name in basic if name != "第一卷"]
    if extra_groups:
        raise ValueError(f"refusing to flatten mixed 基本设定 groups: {', '.join(extra_groups)}")
    data["基本设定"] = dict(volume)
    for _chapter, name, _desc in CHAPTERS:
        if name in data["基本设定"] and is_leaf(data["基本设定"][name]):
            data["基本设定"][name]["section"] = "基本设定"
    validate(data)
    return True


def add_basic_settings(data):
    if "基本设定" in data:
        validate(data)
        return data
    if "作品设定" not in data:
        raise ValueError("missing 作品设定; cannot place 基本设定 after it")

    before = count_leaves(data)
    volume = {
        name: {"section": "基本设定", "desc": desc.strip()}
        for _chapter, name, desc in CHAPTERS
    }
    ordered = {}
    for category, value in data.items():
        ordered[category] = value
        if category == "作品设定":
            ordered["基本设定"] = volume

    validate(ordered)
    after = count_leaves(ordered)
    if after != before + len(CHAPTERS):
        raise ValueError(f"unexpected entry count: {before} -> {after}")
    return ordered


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true", help="write the validated entries to wiki.json")
    args = parser.parse_args()
    data = json.loads(WIKI_PATH.read_text(encoding="utf-8"))
    if "基本设定" in data:
        changed = flatten_basic_settings(data)
        if not changed:
            print(f"already present: {validate(data)} 基本设定 entries")
            return
        if not args.apply:
            raise SystemExit("run with --apply to flatten 基本设定")
        WIKI_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"flattened: {len(CHAPTERS)} entries; total={count_leaves(data)}")
        return
    if not args.apply:
        raise SystemExit("run with --apply to write the new entries")
    result = add_basic_settings(data)
    WIKI_PATH.write_text(json.dumps(result, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"added: {len(CHAPTERS)} entries; total={count_leaves(result)}")


if __name__ == "__main__":
    main()
